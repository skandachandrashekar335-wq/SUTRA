/**
 * SUTRA — Shared Domain Types
 *
 * These types define the core data model. In Phase 1, they serve as the
 * contract between UI and the (not-yet-wired) backend. In subsequent phases,
 * Supabase row types will be derived from / validated against these.
 */

// ─── Enumerations ─────────────────────────────────────────────────────────────

export type LectureStatus = "setup" | "live" | "ended";

/**
 * Moderation status pipeline:
 *   submitted → (auto-moderation) → approved | rejected | needs_review
 *   needs_review → (teacher action) → approved | rejected
 */
export type ModerationStatus =
  | "pending"       // Newly submitted, awaiting moderation
  | "approved"      // Safe and visible in feed
  | "rejected"      // Rejected by auto-moderation or teacher
  | "needs_review"; // Ambiguous — held for teacher decision

export type QuestionGroupStatus = "active" | "resolved";

// ─── Core Entities ────────────────────────────────────────────────────────────

export interface Lecture {
  id: string;
  title: string;
  subject: string;
  section?: string;           // Optional class/section label
  join_code: string;          // 6-character alphanumeric join code
  status: LectureStatus;
  teacher_id: string;         // Opaque teacher session token (Phase 2)
  created_at: string;         // ISO 8601
  started_at?: string;
  ended_at?: string;
}

/**
 * A raw submission from a student.
 * The original wording is always preserved separately from any canonical form.
 */
export interface Doubt {
  id: string;
  lecture_id: string;
  /** Exact text as submitted by the student. Never modified. */
  original_text: string;
  /** Typo-corrected, safe wording produced by the text-processing pipeline.
   *  Null until the pipeline has processed this doubt. */
  cleaned_text: string | null;
  moderation_status: ModerationStatus;
  /** Reason for rejection or review flag — never surfaced verbatim to students */
  moderation_note: string | null;
  /** Foreign key to the confusion group this doubt belongs to, if any. */
  group_id: string | null;
  submitted_at: string;
  /** Ephemeral session token so the submitter can track their own submission */
  session_token: string;
}

/**
 * A canonical confusion group. Multiple related doubts may belong to one group.
 * Grouping must never merge doubts about genuinely distinct concepts.
 */
export interface DoubtGroup {
  id: string;
  lecture_id: string;
  /** The representative question shown to teachers and students */
  canonical_question: string;
  subject_tag: string | null;     // e.g. "Statistics", "Recursion"
  status: QuestionGroupStatus;
  total_submissions: number;      // Count of doubts in this group
  vote_count: number;             // Sum of "Me too" votes across doubts in group
  rank: number | null;            // 1–3 in the Top 3 list, null otherwise
  created_at: string;
  /** Suggested re-explanation snippet (Phase 2: generated by NLP pipeline) */
  explanation_suggestion: string | null;
}

/**
 * An anonymous "Me too" vote on a doubt group.
 * session_token identifies the voter without storing any PII.
 */
export interface Vote {
  id: string;
  group_id: string;
  session_token: string;
  created_at: string;
}

// ─── View / Derived Models ────────────────────────────────────────────────────

/** Enriched group for teacher dashboard display */
export interface RankedGroup extends DoubtGroup {
  doubts: Omit<Doubt, "original_text" | "session_token">[]; // No raw text for teacher view
  is_top3: boolean;
}

/** Student-facing doubt, never exposing other students' session tokens */
export interface PublicDoubt {
  id: string;
  lecture_id: string;
  displayed_text: string;   // cleaned_text if available, else original_text
  moderation_status: "approved" | "pending";
  group_id: string | null;
  submitted_at: string;
  /** Whether the current session has voted "Me too" on this doubt's group */
  viewer_voted?: boolean;
}

// ─── Form Schemas (raw input, pre-validation) ──────────────────────────────────

export interface CreateLectureInput {
  title: string;
  subject: string;
  section?: string;
}

export interface SubmitDoubtInput {
  lecture_id: string;
  text: string;
  session_token: string;
}

export interface JoinLectureInput {
  join_code: string;
}

// ─── API Response Shapes ───────────────────────────────────────────────────────

export type ApiSuccess<T> = {
  ok: true;
  data: T;
};

export type ApiError = {
  ok: false;
  error: string;
  field?: string;
};

export type ApiResponse<T> = ApiSuccess<T> | ApiError;

